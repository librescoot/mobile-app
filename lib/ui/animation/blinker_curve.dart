double blinkerBrightness(Duration phase) {
  final milliseconds = phase.inMicroseconds / Duration.microsecondsPerMillisecond;
  final cycleMilliseconds = blinkerCycle.inMilliseconds;
  final wrapped = milliseconds % cycleMilliseconds;
  final position = wrapped / _blinkerSampleMilliseconds;
  final index = position.floor();
  if (index >= _blinkerBrightness.length) return 0;
  final next = index + 1 < _blinkerBrightness.length ? index + 1 : index;
  final fraction = position - index;
  return _blinkerBrightness[index] * (1 - fraction) + _blinkerBrightness[next] * fraction;
}
